create function public.is_teacher_for(p_student_id uuid)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.teacher_students ts
    join public.teachers t on t.id = ts.teacher_id
    where ts.student_id = p_student_id and ts.active and t.user_id = auth.uid()
  );
$$;

create function public.can_read_student(p_student_id uuid)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.students s where s.id = p_student_id and s.user_id = auth.uid())
      or public.is_teacher_for(p_student_id)
      or exists (select 1 from public.parent_students ps
                 where ps.student_id = p_student_id and ps.parent_user_id = auth.uid() and ps.active);
$$;

create function public.can_read_finances(p_student_id uuid, p_teacher_id uuid)
returns boolean language sql stable security definer set search_path = ''
as $$
  select (public.is_teacher_for(p_student_id) and exists
    (select 1 from public.teachers t where t.id = p_teacher_id and t.user_id = auth.uid()))
      or exists (select 1 from public.students s where s.id = p_student_id and s.user_id = auth.uid())
      or exists (select 1 from public.parent_students ps where ps.student_id = p_student_id
        and ps.parent_user_id = auth.uid() and ps.active and ps.can_view_finances);
$$;

revoke all on function public.is_teacher_for(uuid) from public;
revoke all on function public.can_read_student(uuid) from public;
revoke all on function public.can_read_finances(uuid,uuid) from public;
grant execute on function public.is_teacher_for(uuid) to authenticated;
grant execute on function public.can_read_student(uuid) to authenticated;
grant execute on function public.can_read_finances(uuid,uuid) to authenticated;

