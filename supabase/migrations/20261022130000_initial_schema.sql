-- Maestro's first local Supabase schema. Existing SQLite files are untouched.
-- UUID row identity is separate from app_id, which lets the existing Flutter
-- screens keep their integer identifiers during the incremental migration.

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'user' check (role in ('user', 'teacher', 'student', 'parent', 'administrator')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.teachers (
  id uuid primary key default gen_random_uuid(),
  app_id bigint generated by default as identity unique not null,
  user_id uuid unique references public.profiles(id),
  name text not null,
  telephone text,
  email text,
  address text,
  status text not null default 'ACTIVE',
  first_name text not null default '',
  last_name text not null default '',
  studio_name text not null default '',
  city text not null default '',
  postal_code text not null default '',
  main_instrument text not null default '',
  other_instruments text not null default '',
  default_lesson_duration integer not null default 60 check (default_lesson_duration > 0),
  default_lesson_price numeric(12,2) not null default 0 check (default_lesson_price >= 0),
  currency text not null default 'CAD' check (char_length(currency) = 3),
  profile_image_path text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.students (
  id uuid primary key default gen_random_uuid(),
  app_id bigint generated by default as identity unique not null,
  user_id uuid unique references public.profiles(id),
  first_name text not null default '',
  family_name text not null default '',
  name text not null,
  email text,
  phone text,
  birthday date,
  status text,
  instrument text,
  level text,
  course_day text,
  course_hour time,
  course_price numeric(12,2) not null default 0,
  present boolean not null default false,
  first_course_status text not null default 'NOTHING',
  next_week_assignment text not null default '',
  this_week_comment text not null default '',
  payment_credit_balance numeric(12,2) not null default 0,
  next_project_id integer not null default 1,
  next_course_id integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint students_status_check check (first_course_status in ('NOTHING','PRESENT','ABSENT','CANCELED','MOVED')),
  constraint students_course_day_check check (course_day is null or course_day in
    ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'))
);

create table public.teacher_students (
  teacher_id uuid not null references public.teachers(id),
  student_id uuid not null references public.students(id),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  primary key (teacher_id, student_id)
);

create table public.parent_students (
  parent_user_id uuid not null references public.profiles(id),
  student_id uuid not null references public.students(id),
  active boolean not null default true,
  can_view_finances boolean not null default false,
  created_at timestamptz not null default now(),
  primary key (parent_user_id, student_id)
);

create table public.projects (
  id uuid primary key default gen_random_uuid(),
  app_id bigint generated by default as identity unique not null,
  student_id uuid not null references public.students(id),
  name text not null,
  paid_course_count integer not null default 0 check (paid_course_count >= 0),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (student_id, id)
);

create table public.lessons (
  id uuid primary key default gen_random_uuid(),
  app_id bigint generated by default as identity unique not null,
  student_id uuid not null references public.students(id),
  project_id uuid not null,
  teacher_id uuid references public.teachers(id),
  title text not null,
  day text,
  lesson_date date,
  hour time,
  duration_minutes integer check (duration_minutes is null or duration_minutes > 0),
  price numeric(12,2) not null default 0,
  status text not null default 'NOTHING' check (status in ('NOTHING','PRESENT','ABSENT','CANCELED','MOVED')),
  assignment text not null default '',
  comment text not null default '',
  homework_next_lesson text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (student_id, id),
  foreign key (student_id, project_id) references public.projects(student_id, id)
);

create table public.pieces (
  id uuid primary key default gen_random_uuid(),
  app_id bigint generated by default as identity unique not null,
  student_id uuid not null references public.students(id),
  project_id uuid not null,
  title text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  foreign key (student_id, project_id) references public.projects(student_id, id)
);

create table public.lesson_notes (
  id uuid primary key default gen_random_uuid(),
  app_id bigint generated by default as identity unique not null,
  student_id uuid not null references public.students(id),
  lesson_id uuid not null,
  teacher_id uuid references public.teachers(id),
  piece text not null default '',
  comment text not null default '',
  created_date date,
  review_weeks integer check (review_weeks is null or review_weeks between 1 and 52),
  review_date date,
  review_status text check (review_status is null or review_status in ('PENDING','ACCEPTED','DISMISSED')),
  source_lesson_id uuid,
  accepted_lesson_id uuid,
  target_lesson_id uuid,
  reviewed_date date,
  review_history text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (student_id, lesson_id) references public.lessons(student_id, id),
  foreign key (student_id, source_lesson_id) references public.lessons(student_id, id),
  foreign key (student_id, accepted_lesson_id) references public.lessons(student_id, id),
  foreign key (student_id, target_lesson_id) references public.lessons(student_id, id)
);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  app_id bigint generated by default as identity unique not null,
  student_id uuid not null references public.students(id),
  teacher_id uuid not null references public.teachers(id),
  amount numeric(12,2) not null,
  currency text not null default 'CAD' check (char_length(currency) = 3),
  payment_date date,
  method text,
  note text,
  correction_of uuid references public.payments(id),
  request_key uuid unique,
  created_at timestamptz not null default now()
);

create table public.legacy_id_map (
